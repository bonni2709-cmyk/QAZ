//! Renders the build-time asset manifest into OUT_DIR for the loading screen.
//!
//! Never fails the build: a missing/invalid manifest becomes an empty pack plus
//! a cargo warning — the game still compiles and runs (silent, untextured).

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=tools/gen_assets.py");
    println!("cargo:rerun-if-changed=assets/manifest.json");

    let manifest_path = PathBuf::from("assets").join("manifest.json");

    if !manifest_path.exists() {
        // best-effort generation; needs python3 + numpy + pillow
        let ok = Command::new("python3")
            .arg("tools/gen_assets.py")
            .status()
            .map(|s| s.success())
            .unwrap_or(false);
        if !ok {
            println!(
                "cargo:warning=assets/manifest.json missing and tools/gen_assets.py could not run \
                 (needs python3 + numpy + pillow) — building with an empty asset pack"
            );
        }
    }

    let out_dir = match env::var("OUT_DIR") {
        Ok(dir) => PathBuf::from(dir),
        Err(_) => {
            eprintln!("build.rs: OUT_DIR is not set");
            std::process::exit(1);
        }
    };
    let dest = out_dir.join("asset_manifest.rs");

    let mut entries: Vec<(String, u64)> = Vec::new();
    match fs::read_to_string(&manifest_path) {
        Ok(json) => match serde_json::from_str::<serde_json::Value>(&json) {
            Ok(value) => {
                if let Some(list) = value.as_array() {
                    for item in list {
                        let path = item.get("path").and_then(|v| v.as_str());
                        let bytes = item.get("bytes").and_then(|v| v.as_u64());
                        if let (Some(path), Some(bytes)) = (path, bytes) {
                            entries.push((path.to_string(), bytes));
                        }
                    }
                } else {
                    println!("cargo:warning=assets/manifest.json is not a JSON array; using empty pack");
                }
            }
            Err(e) => println!("cargo:warning=assets/manifest.json is invalid JSON ({e}); using empty pack"),
        },
        Err(_) => println!("cargo:warning=assets/manifest.json not readable; using empty pack"),
    }

    let mut total: u64 = 0;
    for (_, bytes) in &entries {
        total += bytes;
    }

    let mut out = String::from("// @generated by build.rs — do not edit\n");
    out.push_str("pub static ASSET_MANIFEST: &[AssetManifestEntry] = &[\n");
    for (name, bytes) in &entries {
        let escaped = name.replace('\\', "\\\\").replace('"', "\\\"");
        out.push_str(&format!(
            "    AssetManifestEntry {{ name: \"{}\", bytes: {} }},\n",
            escaped, bytes
        ));
    }
    out.push_str("];\n");
    out.push_str(&format!("pub const ASSET_TOTAL_BYTES: u64 = {};\n", total));

    if let Err(e) = fs::write(&dest, out) {
        eprintln!("build.rs: failed to write {}: {}", dest.display(), e);
        std::process::exit(1);
    }
}
